"""ichiran, raw: one unit per word of ichiran's best segmentation.

ichiran runs in the Docker containers its own docker-compose.yml builds
(README.md); the registry names the main container in ICHIRAN_CONTAINER. The
adapter keeps one ``ichiran-cli -e`` running there, a loop that reads Lisp
forms from stdin and prints each value as one JSON line, so ichiran starts
once per run instead of once per sentence. Per sentence it evaluates what
``ichiran-cli -f`` evaluates, ``(romanize* text :limit 1)``, printed by the same
JSON method, with a ``wordprop-fn`` that adds ichiran's own ``word-info-json``
of each word. Root entries and parts of speech ichiran's JSON leaves out come
from its database, through the same loop.

ichiran normalizes the text before segmenting it (fullwidth digits and letters
to ASCII, halfwidth katakana to fullwidth, 。 to ". ", 〜 to " - "), and its
words are substrings of that normalized text. Each word is found in order in
the normalized text, then mapped back to the input by normalizing ever longer
prefixes of it with ichiran's own ``normalize``. ichiran attempts the whole
sentence, so it is a partition; the gaps it leaves (punctuation, but also text
it cannot analyze) are not output and score as misses. For each word:

- reading: its ``kana``, without ichiran's hint marks (U+200B, U+200C) and the
  spaces it puts between compound parts.
- form, form_reading: for a form ichiran generated by conjugating an entry
  (seq 10,000,000 and up), the root its first ``conj`` names (食べる 【たべる】),
  following ``via`` for a conjugation of a conjugation; otherwise the word's
  ``truetext``, the dictionary spelling ichiran matched (やる for ヤル), read
  as its ``kana``.
- entries: ``seq``, a JMdict id, except for a generated form, whose entries are
  its roots (``from`` in ichiran's conjugation table), the one its first
  ``conj`` names first. A JMdict entry that is also a conjugated form of
  another (叫び of 叫ぶ, です of だ) keeps its own seq first and its roots
  after it. Seqs from 10,000,000 up that are not conjugated forms are
  ichiran's own entries (municipalities, extra words), not JMdict, so they are
  left out.
- kind: from the parts of speech of the first sense ichiran lists, the root's
  for a generated form; for a JMdict entry that is also a conjugated form,
  which ichiran lists no senses for, its own first sense. A number + counter
  is a word.

A compound (始めて+しまった, 勉強+して+います) is one unit whose form, entries
and kind are its primary component's, the word ichiran scores it by. A word
with equally good alternatives (家: いえ or うち) takes the first one's fields
and all of their entries, best first.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from typing import Any

from monosashi.adapters.protocol import serve, spans_in_order, to_hiragana

CONTAINER = os.environ.get("ICHIRAN_CONTAINER", "monosashi-ichiran-main-1")
# The release dump the pinned docker-compose.yml restores (README.md).
DUMP = "ichiran-260118"
# ichiran numbers its own entries and the conjugated forms it generates from here up.
GENERATED_SEQ = 10_000_000
# JMdict's own record of its creation date.
DATE_SEQ = 9_999_999

# Read a form, print its value as JSON, until stdin closes. A form that fails
# prints {"error"} instead, so one bad sentence never ends the loop.
_LOOP = """
(loop for form = (read *standard-input* nil :eof)
      until (eq form :eof)
      do (princ (handler-case (jsown:to-json (eval form))
                  (serious-condition (c)
                    (jsown:to-json (jsown:new-js ("error" (princ-to-string c)))))))
         (terpri)
         (finish-output))
"""

_COPULA = frozenset({"cop", "cop-da"})
_KINDS = {
    "prt": "particle",
    "aux": "auxiliary",
    "aux-v": "auxiliary",
    "aux-adj": "auxiliary",
    "pref": "prefix",
    "suf": "suffix",
    "int": "interjection",
    "exp": "expression",
}
# ichiran's kana hints: U+200C before は/へ read わ/え, U+200B a romaji word break.
_NO_HINTS = str.maketrans("", "", "\u200b\u200c")
_NO_HINTS_OR_SPACES = str.maketrans("", "", "\u200b\u200c ")


def _lisp_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


class _Ichiran:
    """The ichiran-cli loop in the container, started again if it exits."""

    def __init__(self) -> None:
        self.proc: subprocess.Popen[str] | None = None

    def eval(self, form: str) -> Any:
        if self.proc is None or self.proc.poll() is not None:
            self.proc = subprocess.Popen(
                ["docker", "exec", "-i", CONTAINER, "ichiran-cli", "-e", _LOOP],
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                text=True,
                encoding="utf-8",
            )
        assert self.proc.stdin is not None and self.proc.stdout is not None
        self.proc.stdin.write(form + "\n")
        self.proc.stdin.flush()
        line = self.proc.stdout.readline()
        if not line:
            raise RuntimeError(f"ichiran-cli in {CONTAINER} exited ({self.proc.wait()})")
        try:
            value = json.loads(line)
        except json.JSONDecodeError:
            raise RuntimeError(f"ichiran printed a line that is not JSON: {line.strip()[:200]!r}") from None
        if isinstance(value, dict) and "error" in value:
            raise RuntimeError(f"ichiran: {value['error']}")
        return value

    def reset(self) -> None:
        """End the loop, so the next form starts a fresh one; ichiran-cli exits with its docker exec."""
        if self.proc is not None and self.proc.poll() is None:
            self.proc.kill()
            self.proc.wait()
        self.proc = None

    def query(self, sql: str) -> list[list[Any]]:
        rows: list[list[Any]] = self.eval(
            f"(ichiran/conn:with-db nil (postmodern:query {_lisp_string(sql)}))"
        )
        return rows


_ichiran = _Ichiran()
# seq -> its conjugation rows, by id: (from, conjugates from directly, a spelling of from).
_conjugations: dict[int, list[tuple[int, bool, str]]] = {}
# seq -> the parts of speech of its first sense.
_tags: dict[int, list[str]] = {}


def _load_conjugations(seqs: set[int]) -> None:
    missing = sorted(seqs - _conjugations.keys())
    if not missing:
        return
    rows = _ichiran.query(
        'SELECT c.seq, c."from", c.via IS NULL, t.text FROM conjugation c'
        " JOIN (SELECT seq, text FROM kanji_text UNION ALL SELECT seq, text FROM kana_text) t"
        ' ON t.seq = c."from"'
        f" WHERE c.seq IN ({', '.join(map(str, missing))}) ORDER BY c.id"
    )
    for seq in missing:
        _conjugations[seq] = []
    for seq, from_, direct, text in rows:
        _conjugations[seq].append((from_, direct is True, text))


def _entry_tags(seq: int) -> list[str]:
    """The parts of speech of an entry's first sense, from ichiran's database."""
    if seq not in _tags:
        rows = _ichiran.query(
            "SELECT s.ord, sp.text FROM sense s JOIN sense_prop sp ON sp.sense_id = s.id"
            f" WHERE s.seq = {seq} AND sp.tag = 'pos' ORDER BY s.ord, sp.ord"
        )
        _tags[seq] = [tag for ord_, tag in rows if ord_ == rows[0][0]] if rows else []
    return _tags[seq]


def _gloss_tags(gloss: list[dict[str, Any]] | None) -> list[str]:
    """The parts of speech of the first sense in ichiran's gloss JSON (``"pos": "[n,vs]"``)."""
    pos = str(gloss[0].get("pos", "")) if gloss else ""
    return [tag for tag in pos.strip("[]").split(",") if tag]


def _kind(tags: list[str]) -> str:
    """cop anywhere in the first sense makes a copula (です is [aux-v,cop]); else its first tag decides."""
    if _COPULA & set(tags):
        return "copula"
    return _KINDS.get(tags[0], "word") if tags else "word"


def _kana(kana: Any) -> str:
    first = kana[0] if isinstance(kana, list) else kana
    return to_hiragana(str(first).translate(_NO_HINTS_OR_SPACES))


def _split_reading(reading: str) -> tuple[str, str]:
    """``食べる 【たべる】`` as (食べる, たべる); a kana-only entry is its own reading."""
    reading = reading.translate(_NO_HINTS)
    if " 【" in reading:
        form, kana = reading[:-1].split(" 【", 1)
        return form, kana
    return reading, reading


def _root_conj(conj: dict[str, Any]) -> dict[str, Any]:
    """The ``conj`` that names the root, following ``via`` past intermediate forms."""
    while "reading" not in conj and conj.get("via"):
        conj = conj["via"][0]
    return conj


def _roots(seq: int, conj: list[dict[str, Any]]) -> list[int]:
    """The JMdict entries ``seq`` is conjugated from, those its ``conj`` names first, in that order.

    As ichiran's ``select-conjs`` does, the rows that conjugate an entry
    directly are used, or all of them when there are none.
    """
    rows = _conjugations.get(seq, [])
    rows = [r for r in rows if r[1]] or rows
    named = [_split_reading(_root_conj(c).get("reading", ""))[0] for c in conj]
    matched = [f for spelling in named for f, _, text in rows if text == spelling]
    roots = list(dict.fromkeys(matched or [r[0] for r in rows]))
    return [r for r in roots if r < GENERATED_SEQ]


def _conjugated(g: dict[str, Any]) -> set[int]:
    """The seqs in one word's gloss JSON that may be conjugated forms."""
    seq = g.get("seq")
    found = {seq} if isinstance(seq, int) and (seq >= GENERATED_SEQ or g.get("conj")) else set()
    for part in g.get("alternative", []) + g.get("components", []):
        found |= _conjugated(part)
    return found


def _word(g: dict[str, Any], w: dict[str, Any]) -> dict[str, Any] | None:
    """form, form_reading, entries and kind of one word, or None for a gap.

    ``g`` is the word as ``ichiran-cli -f`` prints it, ``w`` its ``word-info-json``.
    """
    if w["alternative"] is True:
        options = [o for o in map(_word, g["alternative"], w["components"]) if o is not None]
        if not options:
            return None
        entries = [e for o in options for e in o["entries"]]
        return options[0] | {"entries": list(dict.fromkeys(entries))}
    if w["components"]:
        primary = next((i for i, c in enumerate(w["components"]) if c["primary"] is True), 0)
        return _word(g["components"][primary], w["components"][primary])
    if w["type"] == "GAP":
        return None
    seq = g["seq"] if isinstance(g.get("seq"), int) else None
    own = {
        "form": w["truetext"] if isinstance(w["truetext"], str) else w["text"],
        "form_reading": _kana(w["kana"]),
        "entries": [seq] if seq is not None and seq < GENERATED_SEQ else [],
    }
    if seq is None or "counter" in g:
        return own | {"kind": "word"}
    conj = g.get("conj") or []
    if seq < GENERATED_SEQ:
        tags = _gloss_tags(g["gloss"]) if g.get("gloss") else _entry_tags(seq)
        return own | {
            "entries": list(dict.fromkeys([seq, *_roots(seq, conj)])) if conj else [seq],
            "kind": _kind(tags),
        }
    roots = _roots(seq, conj)
    if not conj:
        # One of ichiran's own entries, or a generated form it names no root for.
        return own | {
            "entries": roots,
            "kind": _kind(_entry_tags(roots[0]) if roots else _gloss_tags(g.get("gloss"))),
        }
    root = _root_conj(conj[0])
    form, form_reading = _split_reading(root["reading"])
    return {
        "form": form,
        "form_reading": form_reading,
        "entries": roots,
        "kind": _kind(_gloss_tags(root.get("gloss"))),
    }


def _original_spans(text: str, prefixes: list[str]) -> list[tuple[int, int]]:
    """The span of ``text`` each character of its normalized form came from.

    ``prefixes`` are ichiran's normalizations of ``text[:1]``, ``text[:2]``, …
    The characters a new input character adds come from it (３ → 3, 。 → ". "),
    and the characters it rewrites (カ then ゛ → ガ) are merged with it.
    """
    spans: list[tuple[int, int]] = []
    prev = ""
    for i, cur in enumerate(prefixes):
        same = 0
        while same < min(len(prev), len(cur)) and prev[same] == cur[same]:
            same += 1
        start = spans[same][0] if same < len(spans) else i
        spans = spans[:same] + [(start, i + 1)] * (len(cur) - same)
        prev = cur
    return spans


def analyze(text: str) -> list[dict[str, Any]]:
    """The units of one sentence; any failure restarts the loop before it is reported.

    A form that prints a line of its own (JSON or not) puts every later answer
    one line behind, each sentence getting the previous one's analysis. A
    line that is not JSON, an answer of the wrong shape, or a word that is not
    in the sentence are the signs of that, so the next sentence starts afresh.
    """
    try:
        return _units(text)
    except Exception:
        _ichiran.reset()
        raise


def _units(text: str) -> list[dict[str, Any]]:
    pieces, prefixes = _ichiran.eval(
        f"(let ((text {_lisp_string(text)}))"
        " (list (ichiran:romanize* (copy-seq text) :limit 1"
        " :wordprop-fn (lambda (r w) (declare (ignore r)) (ichiran/dict:word-info-json w)))"
        " (unless (string= (ichiran/characters:normalize (copy-seq text)) text)"
        " (loop for i from 1 to (length text) collect (ichiran/characters:normalize (subseq text 0 i))))))"
    )
    # A string piece is text between Japanese runs; a run is a list of
    # segmentations, each [[[romanized, gloss JSON, word-info-json], ...], score].
    words = [(g, w) for piece in pieces if isinstance(piece, list) and piece for _, g, w in piece[0][0]]
    _load_conjugations({seq for g, _ in words for seq in _conjugated(g)})
    normalized = prefixes[-1] if prefixes else text
    spans = _original_spans(text, prefixes) if prefixes else None
    units = []
    for (g, w), at in zip(words, spans_in_order(normalized, [w["text"] for _, w in words]), strict=True):
        fields = _word(g, w)
        if fields is None:
            continue
        if at is None:
            raise RuntimeError(f"ichiran's word {w['text']!r} is not in the sentence")
        start, end = (spans[at[0]][0], spans[at[1] - 1][1]) if spans is not None else at
        units.append(
            {
                "start": start,
                "end": end,
                "surface": text[start:end],
                "kind": fields["kind"],
                "form": fields["form"],
                "reading": _kana(w["kana"]),
                "form_reading": to_hiragana(fields["form_reading"]),
                "entries": fields["entries"],
            }
        )
    return units


def _describe() -> dict[str, Any]:
    try:
        created = _ichiran.query(
            "SELECT g.text FROM sense s JOIN gloss g ON g.sense_id = s.id"
            f" WHERE s.seq = {DATE_SEQ} ORDER BY s.ord, g.ord"
        )
    except (RuntimeError, OSError, ValueError) as exc:
        sys.exit(
            f"ichiran adapter: no ichiran in container {CONTAINER} ({exc}); see adapters/ichiran/README.md"
        )
    # "Japanese-Multilingual Dictionary Project - Creation Date: 2026-01-01"
    date = re.search(r"\d{4}-\d{2}-\d{2}", created[0][0]) if created else None
    if date is None:
        sys.exit(f"ichiran adapter: the database has no JMdict creation date (entry {DATE_SEQ})")
    commit = subprocess.run(
        [
            "docker",
            "exec",
            CONTAINER,
            "git",
            "-C",
            "/root/quicklisp/local-projects/ichiran",
            "rev-parse",
            "HEAD",
        ],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    return {
        "name": "ichiran",
        "version": f"ichiran {commit[:7]}, database {DUMP}",
        "commit": commit,
        "dictionary": f"JMdict in ichiran's {DUMP} database dump, with its errata",
        "dictionary_date": date.group(0),
        "partition": True,
        "fields": ["form", "reading", "form_reading", "entries", "kind"],
    }


def main() -> None:
    # Also the check that the container is up, before any sentence is read.
    serve(analyze, _describe())


if __name__ == "__main__":
    main()
