"""himotoki-rs through its Python bindings, raw: one unit per word himotoki outputs.

Runs in adapters/himotoki/.venv (see README.md), with src/ on PYTHONPATH for the
protocol only. The engine reads HIMOTOKI_DB_PATH and HIMOTOKI_MAX_TEXT_LENGTH,
which the registry sets.

himotoki returns ichiran's word list: words, plus gaps for text it cannot
analyze (punctuation, but also onomatopoeia, kana runs, some names). It
attempts the whole sentence, so it is a partition; gaps are not output and
score as misses. For each word:

- surface: its ``text``; offsets are its position in the list, which covers the
  sentence end to end.
- reading: its ``kana``, without the space ichiran puts between a noun and its
  する (べんきょう しています).
- form, form_reading: for a form himotoki generated by conjugating an entry
  (seq 10,000,000 and up), its ``conj`` reading (食べる 【たべる】); otherwise
  the word itself, read as ``kana``.
- entries: ``seq``, a JMdict id, except for a generated form, whose entries are
  the roots it was conjugated from (the ``from`` of its rows in himotoki's own
  conjugation table). A JMdict entry that is also a conjugated form of another
  (叫び of 叫ぶ, です of だ) keeps its own seq first and its roots after it.
- kind: from the parts of speech of the first sense himotoki lists (for a
  counter, its counter sense); for a JMdict entry that is also a conjugated
  form, which himotoki lists no senses for, its own first sense.

A compound (始めて+しまった, 勉強+して+います) is one unit whose form, entries
and kind are its primary component's, as in ichiran's adapter. himotoki's JSON
does not mark the primary component; himotoki always makes it the first.

A word with alternatives (本: ほん or もと) takes the best-scored one's fields,
reading included, and all of their entries, best first, as ichiran's adapter
does. himotoki itself lists a compound alternative first whatever its score:
彼+ら (96) before the entry 彼ら (192), 読み+方 before 読み方. ichiran ranks by
score, so both adapters report 彼ら and 読み方, not 彼 and 読む.
"""

from __future__ import annotations

import sqlite3
from pathlib import Path
from typing import Any

import himotoki_rs

from monosashi.adapters.protocol import serve, to_hiragana

# The pin in README.md: the commit the wheel and the database are built from.
COMMIT = "12ed2eb315e01455a918a9144d5e34f400d3cf13"
JMDICT_DATE = "2026-01-02"  # "JMdict created" in the commit's data/JMdict_e.xml
# himotoki-load numbers the conjugated forms it generates from here up.
GENERATED_SEQ = 10_000_000

_COPULA = frozenset({"cop", "cop-da"})
_KINDS = {
    "prt": "particle",
    "aux": "auxiliary",
    "aux-v": "auxiliary",
    "aux-adj": "auxiliary",
    "pref": "prefix",
    "suf": "suffix",
    "int": "interjection",
    "exp": "expression",
}

himotoki_rs.warm_up()
_db = sqlite3.connect(Path(himotoki_rs.db_path()).as_uri() + "?mode=ro&immutable=1", uri=True)


def _kind(tags: list[str]) -> str:
    """cop anywhere in the first sense makes a copula (です is [aux-v,cop]); else its first tag decides."""
    if _COPULA & set(tags):
        return "copula"
    return _KINDS.get(tags[0], "word") if tags else "word"


def _gloss_tags(gloss: list[dict[str, Any]] | None) -> list[str]:
    """The tags of the first sense in himotoki's gloss JSON (``"pos": "[n,vs]"``)."""
    pos = str(gloss[0].get("pos", "")) if gloss else ""
    return [tag for tag in pos.strip("[]").split(",") if tag]


def _entry_tags(seq: int) -> list[str]:
    """The tags of an entry's first sense, from himotoki's database."""
    rows = _db.execute(
        "SELECT s.ord, sp.text FROM sense s JOIN sense_prop sp ON sp.sense_id = s.id"
        " WHERE s.seq = ? AND sp.tag = 'pos' ORDER BY s.ord, sp.ord",
        (seq,),
    ).fetchall()
    return [tag for ord_, tag in rows if ord_ == rows[0][0]] if rows else []


def _split_reading(reading: str) -> tuple[str, str]:
    """``食べる 【たべる】`` as (食べる, たべる); a kana-only entry is its own reading."""
    if " 【" in reading:
        form, kana = reading[:-1].split(" 【", 1)
        return form, kana
    return reading, reading


def _entry_reading(seq: int) -> str:
    """The reading string himotoki prints for an entry: its first kanji and first kana spelling."""
    kanji = _db.execute("SELECT text FROM kanji_text WHERE seq = ? AND ord = 0", (seq,)).fetchone()
    kana = _db.execute("SELECT text FROM kana_text WHERE seq = ? AND ord = 0", (seq,)).fetchone()
    kana_text = kana[0] if kana else ""
    return f"{kanji[0]} 【{kana_text}】" if kanji else kana_text


def _roots(seqs: list[int], conj: list[dict[str, Any]]) -> list[int]:
    """The entries a conjugated form comes from, in the order its ``conj`` lists them."""
    query = 'SELECT "from" FROM conjugation WHERE seq = ? ORDER BY id'
    froms = [f for seq in seqs for (f,) in _db.execute(query, (seq,))]
    readings = {c["reading"] for c in conj}
    matched = [f for f in froms if _entry_reading(f) in readings]
    return list(dict.fromkeys(matched or froms or seqs))


def _kana(w: dict[str, Any]) -> str:
    kana = w["kana"][0] if isinstance(w["kana"], list) else w["kana"]
    return to_hiragana("".join(str(kana).split()))


def _word(w: dict[str, Any]) -> dict[str, Any] | None:
    """form, reading, form_reading, entries and kind of one word, or None for a gap."""
    if "alternative" in w:
        # Best score first, as ichiran lists them; himotoki puts compounds first.
        ranked = sorted(w["alternative"], key=lambda o: -o.get("score", 0))
        options = [o for o in map(_word, ranked) if o is not None]
        if not options:
            return None
        entries = [e for o in options for e in o["entries"]]
        return options[0] | {"entries": list(dict.fromkeys(entries))}
    if "components" in w:
        primary = _word(w["components"][0])
        return None if primary is None else primary | {"reading": _kana(w)}
    if "seq" not in w:
        return None
    seqs = w["seq"] if isinstance(w["seq"], list) else [w["seq"]]
    own = {"form": w["text"], "reading": _kana(w), "form_reading": _kana(w), "entries": seqs}
    if not w.get("conj"):
        return own | {"kind": _kind(_gloss_tags(w.get("gloss")))}
    roots = _roots(seqs, w["conj"])
    if seqs[0] < GENERATED_SEQ:
        entries = list(dict.fromkeys(seqs + roots))
        return own | {"entries": entries, "kind": _kind(_entry_tags(seqs[0]))}
    form, form_reading = _split_reading(w["conj"][0]["reading"])
    kind = _kind(_gloss_tags(w["conj"][0].get("gloss")))
    return own | {"form": form, "form_reading": form_reading, "entries": roots, "kind": kind}


def analyze(text: str) -> list[dict[str, Any]]:
    results = himotoki_rs.analyze(text)
    words = results[0][0] if results else []
    units = []
    pos = 0
    for w in words:
        start, end = pos, pos + len(w["text"])
        pos = end
        fields = _word(w)
        if fields is None:
            continue
        units.append(
            {
                "start": start,
                "end": end,
                "surface": w["text"],
                "kind": fields["kind"],
                "form": fields["form"],
                "reading": fields["reading"],
                "form_reading": to_hiragana(fields["form_reading"]),
                "entries": fields["entries"],
            }
        )
    return units


def main() -> None:
    serve(
        analyze,
        {
            "name": "himotoki",
            "version": f"himotoki-rs {himotoki_rs.__version__}",
            "commit": COMMIT,
            "dictionary": "JMdict_e bundled with himotoki-rs, with its errata",
            "dictionary_date": JMDICT_DATE,
            "partition": True,
            "fields": ["form", "reading", "form_reading", "entries", "kind"],
        },
    )


if __name__ == "__main__":
    main()
